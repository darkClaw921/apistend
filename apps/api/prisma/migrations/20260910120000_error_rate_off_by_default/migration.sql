-- Инъекция случайных ошибок выключается по умолчанию.
--
-- Прежний умолчательный процент отдавал 500 примерно на каждом двадцатом
-- вызове. Никто его не выбирал: он приходил вместе с песочницей, а читался как
-- нестабильность стенда — разработчик добавлял повторы и уносил их в бой,
-- где каждый повтор стоит настоящего окна лимита.
ALTER TABLE "sandboxes" ALTER COLUMN "errorRate" SET DEFAULT 0;

-- Песочницам, где стоит ровно прежнее умолчание, возвращаем ноль: этой доли
-- никто не назначал. Всё остальное — осознанный выбор, и его не трогаем.
UPDATE "sandboxes" SET "errorRate" = 0 WHERE "errorRate" = 5;
