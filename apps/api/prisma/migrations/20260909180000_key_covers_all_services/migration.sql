-- Ключ песочницы открывает все сервисы стенда.
--
-- Деление ключа по сервисам убрано. Оно ничего не защищало — песочница и так
-- изолирована самим ключом, — зато в день появления нового сервиса оставляло
-- без него все выданные раньше ключи. Пользователь при этом видел в консоли
-- «Добавьте сервис ключу или создайте новый», хотя первое сделать было нечем,
-- а второе означает поменять строку ключа во всех конфигах, куда она прописана.
--
-- Колонка services не удаляется: её показывает таблица ключей и отдаёт
-- Management API. Но раз проверка по ней снята, оставить в ней старый неполный
-- набор значило бы показывать неправду — ключ открывает больше, чем в ней
-- написано. Поэтому набор приводится к полному.
--
-- Отозванные ключи не трогаем: они ничего не открывают, и менять запись о том,
-- на что они были выданы, — переписывать историю.
UPDATE "api_keys"
SET "services" = ARRAY['bitrix24', 'ozon', 'wildberries', 'apify']
WHERE "status" <> 'revoked';
